import { createRequire } from 'module';
const require = createRequire('/opt/uttra-browser/');
const { chromium } = require('playwright');
const URL = process.argv[2] || 'http://127.0.0.1:3000/';
const b = await chromium.launch();
const open = async () => { const c = await b.newContext({ viewport: { width: 390, height: 800 } }); const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); await p.goto(URL + '#/moms'); await p.waitForTimeout(1200); return { c, p, errs }; };
const list = p => p.$$eval('#momList .card, #momList > *', els => els.map(e => e.innerText.trim()));
const A = await open();
console.log('A initial', JSON.stringify(await list(A.p)));
await A.p.screenshot({ path: '/workspace/.browser/moms-empty.png' });
await A.p.fill('#momForm [name=child_name]', 'اختبار');
await A.p.fill('#momForm [name=message]', 'رسالة اختبار آلية');
await A.p.click('#momForm button[type=submit]');
await A.p.waitForTimeout(1200);
console.log('A after send', JSON.stringify(await list(A.p)));
await A.p.screenshot({ path: '/workspace/.browser/moms-sent.png' });
await A.p.reload(); await A.p.waitForTimeout(1200);
console.log('A after reload', JSON.stringify(await list(A.p)));
const B = await open();
console.log('B (new browser)', JSON.stringify(await list(B.p)));
console.log('errors', A.errs, B.errs);
await b.close();
