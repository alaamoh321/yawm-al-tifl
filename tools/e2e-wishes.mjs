import { createRequire } from 'module';
const require = createRequire('/opt/uttra-browser/');
const { chromium } = require('playwright');
const URL = process.argv[2] || 'http://127.0.0.1:3000/';
const b = await chromium.launch();
const open = async (r) => { const c = await b.newContext({ viewport: { width: 390, height: 800 } }); const p = await c.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); await p.goto(URL + '#/' + r); await p.waitForTimeout(1200); return { p, errs }; };
const txt = (p, s) => p.$$eval(s + ' > *', els => els.map(e => e.innerText.trim()));
const A = await open('wishes');
console.log('wishes initial', JSON.stringify(await txt(A.p, '#wishList')));
await A.p.screenshot({ path: '/workspace/.browser/wishes-empty.png' });
await A.p.goto(URL + '#/moms'); await A.p.waitForTimeout(500);
console.log('moms initial', JSON.stringify(await txt(A.p, '#momList')));
await A.p.goto(URL + '#/wishes'); await A.p.waitForTimeout(500);
await A.p.fill('#wishForm [name=name]', 'اختبار');
await A.p.fill('#wishForm [name=wish]', 'أتمنى لك السعادة');
await A.p.click('#wishForm button[type=submit]'); await A.p.waitForTimeout(1200);
console.log('after send', JSON.stringify(await txt(A.p, '#wishList')));
await A.p.screenshot({ path: '/workspace/.browser/wishes-sent.png' });
await A.p.reload(); await A.p.waitForTimeout(1200);
console.log('after reload', JSON.stringify(await txt(A.p, '#wishList')));
console.log('errors', A.errs);
await b.close();
